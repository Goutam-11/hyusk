use super::HyuskState;

/// How far a panel decision reaches.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ApprovalScope {
    /// The stored call only. The phone link is always this scope.
    Once,
    /// The stored call plus later calls with the same tool shape in this turn.
    Turn,
}

#[derive(Debug, Clone)]
pub enum HyuskEvent {
    // Wake system
    WakeWordDetected,

    // User interaction
    UserInput(String),

    /// A transcript produced by a specific microphone capture. The runtime
    /// drops it if that capture is no longer the active listen session.
    VoiceTranscript {
        id: u64,
        text: String,
    },

    /// A normal microphone capture ended without usable speech.
    ListenCompleted {
        id: u64,
        continue_listening: bool,
    },

    /// Run a configured workflow on the deterministic workflow lane.
    RunWorkflow {
        name: String,
    },

    // Continue a just-finished voice conversation without another wake word.
    ContinueListening,
    /// Open a follow-up capture requested by a completed model turn.
    AwaitReplyListening {
        id: u64,
    },
    /// Internal dispatch form for a scheduled prompt; unlike UserInput, this
    /// event must defer while a foreground interaction is active.
    ScheduledAgentInput(String),
    StopListening,
    /// A wake heard during a task is not an interruption until speech follows.
    WakeProbeFinished {
        id: u64,
        text: Option<String>,
    },

    /// Final result from a Nova Sonic listen, scoped to the capture that
    /// produced it so a canceled session cannot update a newer interaction.
    #[cfg(feature = "sonic")]
    SonicListenCompleted {
        id: u64,
        text: Option<String>,
        waiting: bool,
        error: Option<String>,
    },

    // UI state
    StateChanged(HyuskState),

    // Agent/tool activity
    ToolStarted {
        name: String,
    },

    ToolFinished {
        name: String,
        success: bool,
    },

    // Agent output
    Response(String),

    /// A speakable sentence of the reply, delivered while the model is still
    /// generating. Deltas arrive in order and are followed by the final
    /// [`HyuskEvent::Response`] with the complete text.
    ResponseDelta(String),

    // A configured background subagent finished work. This is kept separate
    // from UserInput so it never interrupts the user's current request.
    SubtaskFinished {
        id: u64,
        label: String,
        success: bool,
        summary: String,
    },

    // A persisted schedule became due. Unlike direct user input, this is
    // queued behind an active foreground turn instead of interrupting it.
    ScheduledWorkflow {
        id: u64,
        name: String,
    },
    WorkflowFinished {
        id: u64,
        name: String,
        success: bool,
        summary: String,
    },
    ScheduledAgentTask {
        id: u64,
        prompt: String,
    },

    TurnFinished {
        id: u64,
    },

    // Requested by the GNOME indicator's emergency-stop menu item.
    StopRequested,

    /// Generated by the runtime when an armed tool confirmation reaches its
    /// deadline without an answer.
    ApprovalExpired,

    /// A panel decision for the armed confirmation: GNOME Approve/Deny,
    /// Noctalia, or the phone link. It applies only while a confirmation is
    /// armed, so a stale click reports expiry instead of becoming a user
    /// message or starting a turn.
    ApprovalDecision {
        approved: bool,
        scope: ApprovalScope,
    },

    ModelSelected {
        provider: String,
        model: String,
    },

    /// An API key was saved from the desktop indicator. Only the provider is
    /// carried: the runtime reads the key back from the keyring itself, so a
    /// secret never travels through an event channel.
    ApiKeySaved {
        provider: String,
    },

    // System
    Shutdown,
}
